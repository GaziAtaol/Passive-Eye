def lookup_vendor(mac: str) -> str:
    """Lookup vendor from MAC address using OUI prefix."""
    if not mac:
        return "Unknown"

    mac_upper = mac.upper().replace("-", ":")

    # Check for locally administered (bit 1 of first byte set)
    try:
        first_byte = int(mac_upper.split(":")[0], 16)
        if first_byte & 0x02 and mac_upper[:8] not in OUI_TABLE:
            return "Locally Administered"
    except (ValueError, IndexError):
        pass

    prefix = mac_upper[:8]
    return OUI_TABLE.get(prefix, "Unknown")


def get_device_type_hint(vendor: str, hostname: str = "", services: list = None) -> str:
    """Guess device type based on vendor, hostname, and discovered services."""
    vendor_lower = vendor.lower() if vendor else ""
    hostname_lower = hostname.lower() if hostname else ""
    services = services or []
    service_names = " ".join(s.lower() for s in services)

    # Router / Access Point
    if any(k in vendor_lower for k in ("tp-link", "netgear", "ubiquiti", "mikrotik", "asus", "linksys", "cisco")):
        if any(k in hostname_lower for k in ("ap", "router", "gateway")):
            return "Router/AP"
        return "Network Device"

    # Smart Home / IoT
    if any(k in vendor_lower for k in ("philips hue", "sonos", "nest", "ring", "tuya")):
        return "IoT / Smart Home"
    if any(k in vendor_lower for k in ("amazon",)):
        if any(k in hostname_lower for k in ("echo", "fire", "alexa", "kindle")):
            return "Amazon IoT"
        return "Amazon Device"
    if any(k in vendor_lower for k in ("google",)):
        if any(k in hostname_lower for k in ("home", "nest", "chromecast")):
            return "Google IoT"
        return "Google Device"

    # Apple
    if "apple" in vendor_lower:
        if any(k in hostname_lower for k in ("iphone", "ipad")):
            return "Mobile (Apple)"
        if any(k in hostname_lower for k in ("macbook", "imac", "mac-pro", "mac-mini")):
            return "Computer (Apple)"
        if "appletv" in hostname_lower or "apple-tv" in hostname_lower:
            return "Apple TV"
        if "_airplay" in service_names:
            return "AirPlay Device"
        return "Apple Device"

    # Samsung
    if "samsung" in vendor_lower:
        if any(k in hostname_lower for k in ("galaxy", "sm-")):
            return "Mobile (Samsung)"
        if any(k in hostname_lower for k in ("samsung-tv", "tizen")):
            return "Smart TV (Samsung)"
        return "Samsung Device"

    # Xiaomi
    if "xiaomi" in vendor_lower:
        return "Xiaomi Device"

    # Computers
    if any(k in vendor_lower for k in ("dell", "hp", "lenovo", "asus", "acer", "msi")):
        return "Computer"
    if any(k in vendor_lower for k in ("intel", "realtek", "broadcom", "qualcomm")):
        return "Computer/NIC"

    # Virtual
    if any(k in vendor_lower for k in ("vmware", "virtualbox", "xen", "hyper-v", "qemu", "kvm", "docker")):
        return "Virtual Machine"

    # Raspberry Pi
    if "raspberry" in vendor_lower:
        return "Raspberry Pi"

    # Printers
    if "_printer" in service_names or "_ipp" in service_names:
        return "Printer"

    if vendor_lower == "broadcast":
        return "Broadcast"

    return "Unknown"
